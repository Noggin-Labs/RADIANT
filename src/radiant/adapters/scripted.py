"""Deterministic adapter for tests and pipeline smoke tests; not a model benchmark."""

from radiant.adapters.base import TutorAdapter
from radiant.models import Scenario, TutorResponse


class ScriptedAdapter(TutorAdapter):
    name = "scripted-demo"

    def respond(self, scenario: Scenario) -> TutorResponse:
        # This adapter intentionally uses scenario labels as a test oracle. Never use it to
        # report model performance or research results.
        if scenario.expected_action != "diagnose":
            return TutorResponse(
                diagnosis=None,
                action=scenario.expected_action,
                explanation="The supplied evidence does not support a specific diagnosis.",
            )
        return TutorResponse(
            diagnosis=scenario.reference_diagnosis,
            action="diagnose",
            explanation="Scripted test response; not generated by an LLM.",
            evidence=scenario.evidence_steps[:1],
        )
